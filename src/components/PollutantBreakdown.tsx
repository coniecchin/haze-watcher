import React from 'react';
import { AirQualityData, RegionKey } from '../types/airQuality';
import { Layers, Activity } from 'lucide-react';

interface PollutantBreakdownProps {
  data: AirQualityData;
  selectedRegion: RegionKey;
}

interface PollutantMetric {
  id: string;
  name: string;
  formula: string;
  timeframe: string;
  value: number;
  unit: string;
  thresholdLimit: number; // reference safe ceiling
  description: string;
}

export const PollutantBreakdown: React.FC<PollutantBreakdownProps> = ({
  data,
  selectedRegion,
}) => {
  const current = data.readings[selectedRegion] || data.readings.national;

  const pollutants: PollutantMetric[] = [
    {
      id: 'pm25_1h',
      name: 'Fine Particulate Matter',
      formula: 'PM2.5',
      timeframe: '1-Hour',
      value: current.pm25OneHourly,
      unit: 'µg/m³',
      thresholdLimit: 55, // 55 is NEA Normal Band I ceiling
      description: 'Microscopic combustion particles capable of penetrating deep into lungs and bloodstream.',
    },
    {
      id: 'pm25_24h',
      name: 'Fine Particulate Matter',
      formula: 'PM2.5',
      timeframe: '24-Hour',
      value: current.pm25TwentyFourHourly,
      unit: 'µg/m³',
      thresholdLimit: 37.5,
      description: '24-hour rolling average for chronic respiratory risk modeling.',
    },
    {
      id: 'pm10_24h',
      name: 'Inhalable Particles',
      formula: 'PM10',
      timeframe: '24-Hour',
      value: current.pm10TwentyFourHourly,
      unit: 'µg/m³',
      thresholdLimit: 50,
      description: 'Larger dust, pollen, and smoke particulates irritating upper airways.',
    },
    {
      id: 'o3_8h',
      name: 'Ground-Level Ozone',
      formula: 'O₃',
      timeframe: '8-Hour Max',
      value: current.o3EightHourMax,
      unit: 'µg/m³',
      thresholdLimit: 100,
      description: 'Formed when vehicular and industrial emissions react under intense tropical sunlight.',
    },
    {
      id: 'no2_1h',
      name: 'Nitrogen Dioxide',
      formula: 'NO₂',
      timeframe: '1-Hour Max',
      value: current.no2OneHourMax,
      unit: 'µg/m³',
      thresholdLimit: 200,
      description: 'Emitted from motor vehicles and thermal power generation.',
    },
    {
      id: 'so2_24h',
      name: 'Sulphur Dioxide',
      formula: 'SO₂',
      timeframe: '24-Hour',
      value: current.so2TwentyFourHourly,
      unit: 'µg/m³',
      thresholdLimit: 20,
      description: 'Generated by petrochemical plants, marine bunker fuel, and transboundary smoke.',
    },
  ];

  return (
    <div className="rounded-2xl border border-slate-800 bg-slate-900/80 p-5 shadow-xl backdrop-blur-sm">
      <div className="flex items-center justify-between border-b border-slate-800 pb-4 mb-4">
        <div>
          <div className="flex items-center gap-2">
            <Layers className="w-4 h-4 text-cyan-400" />
            <h3 className="text-sm font-semibold tracking-wider uppercase text-slate-200">
              Multi-Pollutant Concentration Matrix
            </h3>
          </div>
          <p className="text-xs text-slate-400 mt-0.5">
            Station readings at {current.name} vs. Singapore Environmental Protection Standards
          </p>
        </div>

        <span className="text-xs font-mono text-slate-400">
          Source: NEA Air Quality Network
        </span>
      </div>

      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-3.5">
        {pollutants.map((p) => {
          const ratio = Math.min(100, Math.round((p.value / p.thresholdLimit) * 100));
          const isElevated = p.value > p.thresholdLimit;
          const isSevere = ratio >= 150;

          return (
            <div
              key={p.id}
              className="rounded-xl border border-slate-800/80 bg-slate-950/70 p-3.5 flex flex-col justify-between"
            >
              <div>
                <div className="flex items-center justify-between mb-1">
                  <div className="flex items-center gap-1.5">
                    <span className="text-xs font-bold text-slate-200 font-mono">
                      {p.formula}
                    </span>
                    <span className="text-[11px] text-slate-400">·</span>
                    <span className="text-[11px] text-slate-400">{p.timeframe}</span>
                  </div>

                  <span
                    className={`text-[10px] font-mono uppercase font-semibold px-1.5 py-0.5 rounded ${
                      isSevere
                        ? 'bg-rose-500/20 text-rose-300'
                        : isElevated
                        ? 'bg-amber-500/20 text-amber-300'
                        : 'bg-emerald-500/10 text-emerald-400'
                    }`}
                  >
                    {isElevated ? `${ratio}% Limit` : 'Within Limit'}
                  </span>
                </div>

                <div className="text-xs text-slate-300 font-medium truncate">
                  {p.name}
                </div>

                {/* Big Metric Display */}
                <div className="flex items-baseline gap-1 mt-2 mb-2">
                  <span
                    className={`text-2xl font-bold font-mono tabular-nums ${
                      isSevere
                        ? 'text-rose-400'
                        : isElevated
                        ? 'text-amber-400'
                        : 'text-slate-100'
                    }`}
                  >
                    {p.value}
                  </span>
                  <span className="text-xs font-mono text-slate-400">{p.unit}</span>
                  <span className="text-[11px] text-slate-500 font-mono ml-auto">
                    Threshold: {p.thresholdLimit}
                  </span>
                </div>

                {/* Progress bar */}
                <div className="w-full h-1.5 bg-slate-800 rounded-full overflow-hidden mb-2">
                  <div
                    className={`h-full transition-all duration-300 ${
                      isSevere
                        ? 'bg-rose-500'
                        : isElevated
                        ? 'bg-amber-500'
                        : 'bg-cyan-500'
                    }`}
                    style={{ width: `${Math.min(100, ratio)}%` }}
                  />
                </div>
              </div>

              <p className="text-[11px] text-slate-400 leading-tight">
                {p.description}
              </p>
            </div>
          );
        })}
      </div>
    </div>
  );
};
